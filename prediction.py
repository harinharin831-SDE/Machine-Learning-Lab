"""
=============================================================================
KIDNEY DISEASE IMAGE CLASSIFICATION USING MACHINE LEARNING
Module: Single Image Inference & Prediction Pipeline
=============================================================================
This module provides single-image inference:
  1. Accepts user-uploaded image files or arrays
  2. Runs 5-stage digital preprocessing
  3. Extracts multi-descriptor HOG + GLCM feature vector
  4. Applies Scikit-learn Pipeline (StandardScaler + Classifier)
  5. Computes predicted class & confidence estimate (when supported)
  6. Attaches mandatory academic/research disclaimer

Note: For academic and research purposes only. Not for medical diagnosis.
=============================================================================
"""

import numpy as np
from typing import Dict, Any, Union, Optional
import io
from PIL import Image

from preprocessing import preprocess_image
from feature_extraction import extract_features


DISCLAIMER_TEXT = (
    "Model confidence estimate — not a medical probability. "
    "This output is generated by an academic Machine Learning mini-project for "
    "educational demonstration and should NEVER be used for clinical decision-making."
)


def predict_single_image(
    model_package: Dict[str, Any],
    image_input: Union[str, bytes, bytearray, io.BytesIO, Image.Image, np.ndarray]
) -> Dict[str, Any]:
    """
    Executes end-to-end inference on a single kidney ultrasound image.

    Args:
        model_package: Loaded model package dict containing pipeline and class_names.
        image_input: Input image in any format (file path, bytes, PIL, numpy).

    Returns:
        Dict[str, Any]: Inference results containing predicted class, confidence,
                        class probability distribution, preprocessing stages,
                        and feature breakdown.
    """
    if model_package is None or "pipeline" not in model_package:
        raise ValueError("Valid trained model package is required for prediction.")

    pipeline = model_package["pipeline"]
    class_names = model_package.get("class_names", ["Class 0", "Class 1"])

    # 1. Preprocess Image
    prep_results = preprocess_image(image_input)

    # 2. Extract Features (HOG + GLCM) with breakdown
    feature_breakdown = extract_features(prep_results["enhanced"], return_breakdown=True)
    feature_vector = feature_breakdown["feature_vector"].reshape(1, -1)

    # 3. Model Prediction
    predicted_idx = int(pipeline.predict(feature_vector)[0])
    
    # Map index to class name
    if 0 <= predicted_idx < len(class_names):
        predicted_class = class_names[predicted_idx]
    else:
        predicted_class = f"Class {predicted_idx}"

    # 4. Probability / Confidence Estimation
    supports_prob = False
    confidence = None
    prob_dict = {}

    clf = pipeline.named_steps.get("classifier", pipeline)
    if hasattr(pipeline, "predict_proba"):
        try:
            probs = pipeline.predict_proba(feature_vector)[0]
            supports_prob = True
            confidence = float(probs[predicted_idx])
            for i, p in enumerate(probs):
                c_name = class_names[i] if i < len(class_names) else f"Class {i}"
                prob_dict[c_name] = float(p)
        except Exception:
            supports_prob = False

    return {
        "predicted_class": predicted_class,
        "predicted_index": predicted_idx,
        "confidence": confidence,
        "confidence_percent": confidence * 100.0 if confidence is not None else None,
        "probabilities": prob_dict if supports_prob else None,
        "supports_probability": supports_prob,
        "preprocessed_images": prep_results,
        "feature_breakdown": feature_breakdown,
        "algorithm": model_package.get("algorithm", "Machine Learning"),
        "disclaimer": DISCLAIMER_TEXT
    }
